// Cloudflare, so it pins the `node` preset and writes to .output/. Web deploys keep
// Lovable's default preset, which is pinned by LOVABLE_NITRO_PRESET at publish time.
const desktop = process.env["FORGE_DESKTOP"] === "1";

export default defineConfig({
  tanstackStart: {
    // Redirect TanStack Start's bundled server entry to src/server.ts (our SSR error wrapper).
    // nitro/vite builds from this
    server: { entry: "server" },
  },
  ...(desktop ? { nitro: { preset: "node-server" } } : {}),
});
